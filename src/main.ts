import './styles/global.css';
import { socialIcon } from './components/socialIcon';
import { profile, socialLinks } from './data/profile';
import { games } from './data/games';
import { gameCard } from './components/GameCard';
import { element, link, picture, validUrl } from './utils/dom';
import { setupTheme } from './utils/theme';
const app = document.querySelector<HTMLDivElement>('#app')!;
const header = element('header', 'site-header container');
const home = link(profile.name, '#top', 'wordmark');
const mark = element('span', 'brand-mark', 'JC'); mark.setAttribute('aria-hidden', 'true'); home.prepend(mark);
const nav = element('nav'); nav.setAttribute('aria-label', 'Main navigation');
const theme = element('button', 'theme-toggle'); theme.type = 'button';
nav.append(link('About', '#about'), link('Arcade', '#arcade'), theme); header.append(home, nav);
const main = element('main', 'container'); main.id = 'main';
const about = element('section', 'about'); about.id = 'about'; about.setAttribute('aria-labelledby', 'intro-heading');
const portrait = element('div', 'portrait-wrap');
portrait.append(picture(profile.image, 'Jenson Choi enjoying time outdoors', 'JC', 'portrait', false), element('span', 'portrait-caption', 'A little about me'));
const intro = element('div', 'intro');
intro.append(element('p', 'eyebrow', 'ENGINEER. EXPLORER. OCCASIONAL GAME MAKER.'));
const heading = element('h1', '', profile.greeting); heading.id = 'intro-heading'; heading.append(element('span', 'wave', ' 👋')); intro.append(heading);
profile.biography.forEach(paragraph => intro.append(element('p', 'bio', paragraph)));
const socials = element('div', 'socials');
const labels: Record<string, string> = { linkedin: 'LinkedIn', github: 'GitHub', instagram: 'Instagram', threads: 'Threads', x: 'X', email: 'Email', resume: 'Résumé' };
Object.entries(socialLinks).forEach(([platform, value]) => {
  const email = platform === 'email' && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
  if (!email && !validUrl(value)) return;
  const anchor = link(labels[platform] ?? platform, email ? `mailto:${value}` : value, 'social-link', !email);
  anchor.setAttribute('aria-label', labels[platform] ?? platform);
  anchor.title = labels[platform] ?? platform;
  const icon = socialIcon(platform);
  if (icon) anchor.replaceChildren(icon);
  socials.append(anchor);
});
if (socials.childElementCount) intro.append(socials);
intro.append(link('Explore My Arcade ↓', '#arcade', 'explore-link'));
about.append(portrait, intro);
const arcade = element('section', 'arcade'); arcade.id = 'arcade'; arcade.setAttribute('aria-labelledby', 'arcade-heading');
const arcadeHeader = element('div', 'arcade-header');
const titleGroup = element('div'); titleGroup.append(element('p', 'eyebrow', 'SIDE PROJECTS / PLAY TIME'));
const title = element('h2', '', "🎮 Jenson's Arcade"); title.id = 'arcade-heading'; titleGroup.append(title);
arcadeHeader.append(titleGroup, element('span', 'collection-count', `${String(games.length).padStart(2, '0')} GAMES & COUNTING`));
const grid = element('div', 'game-grid'); games.forEach((game, index) => grid.append(gameCard(game, index)));
arcade.append(arcadeHeader, element('p', 'arcade-subtitle', "A collection of games I've been building for fun with a little help from AI. Pick one and give it a try!"), grid);
main.append(about, arcade);
const footer = element('footer', 'container footer'); footer.append(element('p', '', `© ${new Date().getFullYear()} ${profile.name}. Built with curiosity and a little help from AI.`), link('Back to top ↑', '#top'));
app.append(header, main, footer); setupTheme(theme);
